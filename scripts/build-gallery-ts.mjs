// Emit src/gallery.ts from the processed catalog, trimming the fields the UI
// actually needs so the bundle stays lean.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const catalogPath = path.resolve(import.meta.dirname, '../src/gallery.raw.json');
const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));

const categories = catalog.categories.map((c) => ({ id: c.id, zh: c.zh, emoji: c.emoji, count: c.count }));
const entries = catalog.entries.map((e) => ({
  id: e.number,
  title: e.title,
  category: e.category,
  image: e.image,
  size: e.size,
  prompt: e.prompt,
  stylePrompt: e.stylePrompt,
}));

const ts = `// Generated by scripts/build-gallery-ts.mjs — do not edit by hand.
// Prompt gallery distilled from the GPT-Image2-Skill reference gallery.
export type GalleryCategory = { id: string; zh: string; emoji: string; count: number };
export type GalleryEntry = {
  id: number;
  title: string;
  category: string;
  image: string;
  size: string;
  prompt: string;
  stylePrompt: string;
};

export const GALLERY_CATEGORIES: GalleryCategory[] = ${JSON.stringify(categories, null, 2)};

export const GALLERY_ENTRIES: GalleryEntry[] = ${JSON.stringify(entries, null, 2)};
`;

const outPath = path.resolve(import.meta.dirname, '../src/gallery.ts');
writeFileSync(outPath, ts, 'utf8');
console.log(`Wrote ${entries.length} entries, ${categories.length} categories -> ${outPath} (${(ts.length / 1024).toFixed(0)} KB)`);
